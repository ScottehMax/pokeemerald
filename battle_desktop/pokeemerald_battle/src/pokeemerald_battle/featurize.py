"""Featurized observation wrapper for Pokémon battle environments.

Replaces opaque integer IDs (species, moves, abilities) with meaningful
numerical features that a neural network can learn from:

- Move features: power, accuracy, type one-hot, physical/special/status,
  STAB bonus, type effectiveness vs opponent, PP fraction
- Active mon features: HP fraction, stat stages (normalised), types one-hot,
  status flags
- Party features: HP fractions, alive counts
- Field features: weather, side conditions, spikes

All values are normalised to approximately [0, 1] or [-1, 1].
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any

import gymnasium as gym
import numpy as np
from gymnasium import spaces

from pokeemerald_battle._ffi import (
    BATTLE_MAX_BATTLERS,
    BATTLE_MAX_MOVES,
    BATTLE_NUM_SIDES,
    BATTLE_PARTY_SIZE,
)

# ---------------------------------------------------------------------------
# Game data constants
# ---------------------------------------------------------------------------

NUM_TYPES = 18  # Normal(0) through Dark(17); Mystery(9) treated as Normal

# Gen 3 physical/special split is by type, not by move
PHYSICAL_TYPES = {0, 1, 2, 3, 4, 5, 6, 7, 8}  # Normal..Steel
SPECIAL_TYPES = {10, 11, 12, 13, 14, 15, 16, 17}  # Fire..Dark

# Type effectiveness chart: effectiveness[atk_type][def_type] = multiplier
# Default is 1.0 (neutral). Built from the game's gTypeEffectiveness table.
